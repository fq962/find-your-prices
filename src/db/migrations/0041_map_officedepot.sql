-- Mapea las categorias de Office Depot (store_categories) al arbol canonico,
-- acotado a esa tienda.
--
-- Por que aparte de 0036. El mapeo general va por nombre y sin tienda, y los
-- nombres de Office Depot son genericos hasta el extremo: "Accesorios",
-- "Cables", "Rollos", "Pinturas", "Herramientas", "Electrodomesticos". Los
-- mismos nombres en una ferreteria o un supermercado significan otra cosa, asi
-- que se mapea por CODIGO de categoria de la tienda y solo donde
-- store.slug = 'officedepot'. El codigo tambien resuelve los nombres que la
-- propia tienda repite ("Escritura" cuelga de Oficina y de Escolares).
--
-- Criterios de las decisiones menos obvias:
--   - Todo lo de impresion (cartuchos, toner, tinta, impresoras, papel
--     fotografico) cae en 'impresoras' = "Impresoras y Consumibles".
--   - Folders, sobres, carpetas, archivadores, micas y cajas -> 'archivo'.
--   - Los basicos de papeleria (clips, grapas, cintas, notas) y las
--     calculadoras -> 'utiles-escolares-oficina'.
--   - Muebles: escritorios, sillas, mesas, archiveros y libreros ->
--     'muebles-oficina'; la decoracion propiamente dicha -> 'decoracion-muebles'.
--   - Mochilas, loncheras y maletines -> los cajones de moda y viaje, que es
--     donde el comprador los busca.
--
-- Se dejan sin mapear a proposito: ROOT y "Todas" (raices tecnicas del
-- catalogo), "72 Horas Online" (promocion) y "Uncategorized", el cajon de la
-- propia tienda con 209 articulos sin clasificar.
--
-- Solo toca filas con category_id null: lo corregido desde el panel gana.
-- Idempotente.
-- =============================================================================

